export const uiCatalog = Object.fromEntries(
  [...rows, ...homeRows, ...experienceRows, ...newExperienceRows, ...coupleGameRows].map(
    ([en, hi, gu, hinglish, roman]) => [
      en,
      { en, hi, gu, hinglish, "roman-gu": roman },
    ],
  ),
);
export function translate(
  language: Language,
  text: string,
  values: Record<string, string> = {},
) {
  return (uiCatalog[text]?.[language] ?? text).replace(
    /\{(\w+)\}/g,
    (match: string, key: string) => values[key] ?? match,
  );
}
export function readLanguage(): Language {
  try {
    const saved = localStorage.getItem("heartpop-language");
    if (saved && ["en", "hi", "gu", "hinglish", "roman-gu"].includes(saved))
      return saved as Language;
  } catch {
    /* Storage can be disabled. */
  }
  return "en";
}
